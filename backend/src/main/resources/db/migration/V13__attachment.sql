-- V13: files on a ticket. The bytes live in object storage (Silo / MinIO). This table keeps only the facts.
-- UPLOADING: parts are still coming in. READY: upload completed and checked. Soft delete like the other tables.

CREATE TABLE IF NOT EXISTS attachment (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     bigint       NOT NULL,
    uploaded_by   bigint       NOT NULL,
    original_name varchar(255) NOT NULL,
    object_key    varchar(255) NOT NULL,
    upload_id     varchar(255),
    content_type  varchar(100) NOT NULL,
    size_bytes    bigint       NOT NULL,
    status        varchar(20)  NOT NULL DEFAULT 'UPLOADING',
    ready_on      timestamp(6) with time zone,
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT fk_attachment_ticket   FOREIGN KEY (ticket_id)   REFERENCES ticket (id),
    CONSTRAINT fk_attachment_uploader FOREIGN KEY (uploaded_by) REFERENCES users (id),
    CONSTRAINT chk_attachment_size    CHECK (size_bytes > 0 AND size_bytes <= 26214400),
    CONSTRAINT chk_attachment_status  CHECK (status IN ('UPLOADING', 'READY'))
);

-- one object key belongs to one row
CREATE UNIQUE INDEX IF NOT EXISTS uq_attachment_object_key
    ON attachment (object_key);

-- the files of one ticket, oldest first
CREATE INDEX IF NOT EXISTS idx_attachment_ticket
    ON attachment (ticket_id, created_on)
    WHERE deleted_on IS NULL;

-- the cleanup job looks for uploads that never finished
CREATE INDEX IF NOT EXISTS idx_attachment_uploading
    ON attachment (created_on)
    WHERE status = 'UPLOADING' AND deleted_on IS NULL;