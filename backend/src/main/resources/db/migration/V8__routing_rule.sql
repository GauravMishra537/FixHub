-- V8: routing rules.
-- Lookup order for a new ticket: type + category, then type only, then no department.

CREATE TABLE IF NOT EXISTS routing_rule (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_type   varchar(30) NOT NULL,
    category_id   bigint,
    department_id bigint      NOT NULL,
    active        boolean     NOT NULL DEFAULT true,
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT ck_routing_type CHECK (ticket_type IN
        ('ISSUE', 'ROOM_BOOKING', 'RESOURCE_REQUEST', 'TOPIC_REQUEST')),
    CONSTRAINT fk_routing_category   FOREIGN KEY (category_id)   REFERENCES ticket_category (id),
    CONSTRAINT fk_routing_department FOREIGN KEY (department_id) REFERENCES department (id)
);

-- one live rule for each type + category
CREATE UNIQUE INDEX IF NOT EXISTS uq_routing_type_category
    ON routing_rule (ticket_type, category_id)
    WHERE category_id IS NOT NULL AND deleted_on IS NULL;

-- one live "whole type" rule for each type
CREATE UNIQUE INDEX IF NOT EXISTS uq_routing_type_only
    ON routing_rule (ticket_type)
    WHERE category_id IS NULL AND deleted_on IS NULL;

CREATE INDEX IF NOT EXISTS idx_routing_department ON routing_rule (department_id);