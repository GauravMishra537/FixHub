-- V4: Google identities + Google subject on signup request

CREATE TABLE IF NOT EXISTS user_identities (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint       NOT NULL,
    provider         varchar(20)  NOT NULL,
    provider_subject varchar(255) NOT NULL,
    created_on       timestamp(6) with time zone NOT NULL,
    created_by       bigint,
    updated_on       timestamp(6) with time zone NOT NULL,
    updated_by       bigint,
    deleted_on       timestamp(6) with time zone,
    deleted_by       bigint,
    CONSTRAINT fk_identity_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT chk_identity_provider CHECK (provider IN ('GOOGLE'))
);

-- One Google account = one live identity. Soft delete frees it.
CREATE UNIQUE INDEX IF NOT EXISTS uq_identity_provider_subject
    ON user_identities (provider, provider_subject) WHERE deleted_on IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_identity_user_provider
    ON user_identities (user_id, provider) WHERE deleted_on IS NULL;

CREATE INDEX IF NOT EXISTS idx_identity_user ON user_identities (user_id);

ALTER TABLE registration_request ADD COLUMN IF NOT EXISTS google_subject varchar(255);