-- V10: in-app notifications. One row per person who is told something.

CREATE TABLE IF NOT EXISTS notification (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint       NOT NULL,
    type        varchar(40)  NOT NULL,
    ticket_id   bigint,
    message     varchar(255) NOT NULL,
    read_on     timestamp(6) with time zone,
    created_on  timestamp(6) with time zone NOT NULL,
    created_by  bigint,
    updated_on  timestamp(6) with time zone NOT NULL,
    updated_by  bigint,
    deleted_on  timestamp(6) with time zone,
    deleted_by  bigint,
    CONSTRAINT fk_notification_user   FOREIGN KEY (user_id)   REFERENCES users (id),
    CONSTRAINT fk_notification_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id)
);

-- unread count and newest-first list for one person
CREATE INDEX IF NOT EXISTS idx_notification_user_unread
    ON notification (user_id, created_on DESC)
    WHERE read_on IS NULL AND deleted_on IS NULL;

CREATE INDEX IF NOT EXISTS idx_notification_user
    ON notification (user_id, created_on DESC)
    WHERE deleted_on IS NULL;