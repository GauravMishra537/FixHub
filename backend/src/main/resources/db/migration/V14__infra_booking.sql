-- V14: infra booking. Three tables: infra_type (the kind), infrastructure (one unit), booking (one session).
-- A booking request is a ticket. One ticket = one group, its sessions are the booking rows under it.
-- Availability is never stored as a number. It is counted from booking rows, so time passing frees a unit by itself.

-- lets the guard below compare a unit id and a time range in one rule
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------- the kind: Conference Room, Computer Lab ----------
CREATE TABLE IF NOT EXISTS infra_type (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(100) NOT NULL,
    description varchar(255),
    icon        varchar(40),
    -- longest single session without a written reason
    max_minutes integer      NOT NULL DEFAULT 240,
    -- order of the cards on the page
    sort_order  integer      NOT NULL DEFAULT 0,
    active      boolean      NOT NULL DEFAULT true,
    created_on  timestamp(6) with time zone NOT NULL,
    created_by  bigint,
    updated_on  timestamp(6) with time zone NOT NULL,
    updated_by  bigint,
    deleted_on  timestamp(6) with time zone,
    deleted_by  bigint,
    CONSTRAINT ck_infra_type_max_minutes CHECK (max_minutes > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_infra_type_name
    ON infra_type (lower(name))
    WHERE deleted_on IS NULL;

-- ---------- one real unit: Conference Room 3, capacity 6 ----------
CREATE TABLE IF NOT EXISTS infrastructure (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    infra_type_id bigint       NOT NULL,
    name          varchar(100) NOT NULL,
    capacity      integer      NOT NULL,
    location      varchar(100),
    note          varchar(255),
    status        varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT fk_infrastructure_type FOREIGN KEY (infra_type_id) REFERENCES infra_type (id),
    CONSTRAINT ck_infrastructure_capacity CHECK (capacity >= 1 AND capacity <= 1000),
    CONSTRAINT ck_infrastructure_status CHECK (status IN ('ACTIVE', 'OUT_OF_SERVICE'))
);

-- a unit name is unique inside its kind
CREATE UNIQUE INDEX IF NOT EXISTS uk_infrastructure_type_name
    ON infrastructure (infra_type_id, lower(name))
    WHERE deleted_on IS NULL;

-- units of a kind, smallest first (the fit search)
CREATE INDEX IF NOT EXISTS idx_infrastructure_type_capacity
    ON infrastructure (infra_type_id, capacity)
    WHERE deleted_on IS NULL;

-- ---------- one session: this unit, this time, for this meeting ----------
CREATE TABLE IF NOT EXISTS booking (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id        bigint       NOT NULL,
    infrastructure_id bigint      NOT NULL,
    -- the team of the person who booked, kept as it was at booking time
    department_id    bigint,
    title            varchar(200) NOT NULL,
    headcount        integer      NOT NULL,
    start_time       timestamp(6) with time zone NOT NULL,
    end_time         timestamp(6) with time zone NOT NULL,
    all_day          boolean      NOT NULL DEFAULT false,
    status           varchar(20)  NOT NULL DEFAULT 'PENDING',
    -- required for all day, for a session over the kind's limit, and for a bigger room than needed
    reason           varchar(500),
    oversize         boolean      NOT NULL DEFAULT false,
    -- who approved, rejected or cancelled it, when, and the reason typed
    decided_by       bigint,
    decided_on       timestamp(6) with time zone,
    decision_note    varchar(500),
    created_on       timestamp(6) with time zone NOT NULL,
    created_by       bigint,
    updated_on       timestamp(6) with time zone NOT NULL,
    updated_by       bigint,
    deleted_on       timestamp(6) with time zone,
    deleted_by       bigint,
    CONSTRAINT fk_booking_ticket         FOREIGN KEY (ticket_id)         REFERENCES ticket (id),
    CONSTRAINT fk_booking_infrastructure FOREIGN KEY (infrastructure_id) REFERENCES infrastructure (id),
    CONSTRAINT fk_booking_department     FOREIGN KEY (department_id)     REFERENCES department (id),
    CONSTRAINT fk_booking_decided_by     FOREIGN KEY (decided_by)        REFERENCES users (id),
    CONSTRAINT ck_booking_headcount CHECK (headcount >= 1),
    CONSTRAINT ck_booking_time      CHECK (end_time > start_time),
    CONSTRAINT ck_booking_status    CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
    -- the database itself refuses a double booking: same unit, overlapping time, both still holding the slot.
    -- back to back is fine because the range includes the start and leaves out the end.
    -- two people clicking in the same second: the second one fails here.
    CONSTRAINT ex_booking_no_overlap EXCLUDE USING gist (
        infrastructure_id WITH =,
        tstzrange(start_time, end_time, '[)') WITH &&
    ) WHERE (status IN ('PENDING', 'APPROVED') AND deleted_on IS NULL)
);

-- the sessions of one ticket
CREATE INDEX IF NOT EXISTS idx_booking_ticket
    ON booking (ticket_id)
    WHERE deleted_on IS NULL;

-- the board and the free-unit search look at a time window
CREATE INDEX IF NOT EXISTS idx_booking_window
    ON booking (start_time, end_time)
    WHERE status IN ('PENDING', 'APPROVED') AND deleted_on IS NULL;