-- V12: comments on a ticket. One row per comment. Soft delete like the other tables.

CREATE TABLE IF NOT EXISTS ticket_comment (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id   bigint        NOT NULL,
    author_id   bigint        NOT NULL,
    body        varchar(2000) NOT NULL,
    created_on  timestamp(6) with time zone NOT NULL,
    created_by  bigint,
    updated_on  timestamp(6) with time zone NOT NULL,
    updated_by  bigint,
    deleted_on  timestamp(6) with time zone,
    deleted_by  bigint,
    CONSTRAINT fk_ticket_comment_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id),
    CONSTRAINT fk_ticket_comment_author FOREIGN KEY (author_id) REFERENCES users (id)
);

-- the thread of one ticket, oldest first
CREATE INDEX IF NOT EXISTS idx_ticket_comment_ticket
    ON ticket_comment (ticket_id, created_on)
    WHERE deleted_on IS NULL;