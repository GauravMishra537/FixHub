CREATE TABLE entity_audit (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  timestamp(6) with time zone NOT NULL,
    updated_at  timestamp(6) with time zone NOT NULL,
    expired_at  timestamp(6) with time zone,
    deleted_at  timestamp(6) with time zone,
    created_by  bigint,
    updated_by  bigint,
    deleted_by  bigint
);

CREATE TABLE users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          varchar(120) NOT NULL,
    password_hash  varchar(255),
    full_name      varchar(100) NOT NULL,
    role           varchar(20)  NOT NULL,
    status         varchar(20)  NOT NULL,
    department     varchar(100),
    designation    varchar(100),
    phone_number   varchar(30),
    email_verified boolean      NOT NULL,
    audit_id       bigint       NOT NULL,
    CONSTRAINT uq_users_email    UNIQUE (email),
    CONSTRAINT uq_users_audit_id UNIQUE (audit_id),
    CONSTRAINT fk_users_audit    FOREIGN KEY (audit_id) REFERENCES entity_audit (id),
    CONSTRAINT chk_users_role    CHECK (role IN ('ADMIN', 'USER')),
    CONSTRAINT chk_users_status  CHECK (status IN ('PENDING', 'ACTIVE', 'REJECTED', 'SUSPENDED'))
);

ALTER TABLE entity_audit
    ADD CONSTRAINT fk_entity_audit_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    ADD CONSTRAINT fk_entity_audit_updated_by FOREIGN KEY (updated_by) REFERENCES users (id),
    ADD CONSTRAINT fk_entity_audit_deleted_by FOREIGN KEY (deleted_by) REFERENCES users (id);

CREATE TABLE verification_tokens (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token       varchar(100) NOT NULL,
    user_id     bigint       NOT NULL,
    expiry_date timestamp(6) with time zone NOT NULL,
    used        boolean      NOT NULL,
    created_at  timestamp(6) with time zone NOT NULL,
    CONSTRAINT uq_verification_token UNIQUE (token),
    CONSTRAINT fk_verification_user  FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE audit_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  varchar(50) NOT NULL,
    user_id     bigint,
    user_email  varchar(120),
    description varchar(255),
    ip_address  varchar(45),
    created_at  timestamp(6) with time zone NOT NULL
);

CREATE INDEX idx_users_email         ON users (email);
CREATE INDEX idx_users_status        ON users (status);
CREATE INDEX idx_users_role          ON users (role);
CREATE INDEX idx_verification_token  ON verification_tokens (token);
CREATE INDEX idx_verification_user   ON verification_tokens (user_id);
CREATE INDEX idx_audit_event_type    ON audit_logs (event_type);
CREATE INDEX idx_audit_user_id       ON audit_logs (user_id);
CREATE INDEX idx_audit_created_at    ON audit_logs (created_at);