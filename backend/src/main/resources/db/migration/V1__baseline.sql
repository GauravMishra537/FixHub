-- V1: baseline schema (registration_request + users + audit base columns + soft delete)

CREATE TABLE IF NOT EXISTS users (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          varchar(120) NOT NULL,
    password_hash  varchar(255),
    full_name      varchar(100) NOT NULL,
    role           varchar(20)  NOT NULL,
    department     varchar(100),
    designation    varchar(100),
    phone_number   varchar(30),
    last_login_at  timestamp(6) with time zone,
    created_on     timestamp(6) with time zone NOT NULL,
    created_by     bigint,
    updated_on     timestamp(6) with time zone NOT NULL,
    updated_by     bigint,
    deleted_on     timestamp(6) with time zone,
    deleted_by     bigint,
    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'USER'))
);

CREATE TABLE IF NOT EXISTS registration_request (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name        varchar(100) NOT NULL,
    email            varchar(120) NOT NULL,
    password_hash    varchar(255),
    email_verified   boolean      NOT NULL DEFAULT false,
    request_status   varchar(20)  NOT NULL,
    rejection_reason varchar(255),
    reviewed_by      bigint,
    reviewed_on      timestamp(6) with time zone,
    created_on       timestamp(6) with time zone NOT NULL,
    created_by       bigint,
    updated_on       timestamp(6) with time zone NOT NULL,
    updated_by       bigint,
    deleted_on       timestamp(6) with time zone,
    deleted_by       bigint,
    CONSTRAINT chk_request_status CHECK (request_status IN ('PENDING', 'APPROVED', 'REJECTED'))
);

CREATE TABLE IF NOT EXISTS verification_tokens (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token                   varchar(100) NOT NULL,
    registration_request_id bigint       NOT NULL,
    expiry_date             timestamp(6) with time zone NOT NULL,
    used                    boolean      NOT NULL DEFAULT false,
    created_on              timestamp(6) with time zone NOT NULL,
    created_by              bigint,
    updated_on              timestamp(6) with time zone NOT NULL,
    updated_by              bigint,
    deleted_on              timestamp(6) with time zone,
    deleted_by              bigint,
    CONSTRAINT uq_verification_token UNIQUE (token),
    CONSTRAINT fk_verification_request FOREIGN KEY (registration_request_id)
        REFERENCES registration_request (id)
);

CREATE TABLE IF NOT EXISTS audit_logs (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type  varchar(50) NOT NULL,
    user_id     bigint,
    user_email  varchar(120),
    description varchar(255),
    ip_address  varchar(45),
    created_at  timestamp(6) with time zone NOT NULL
);

-- A soft-deleted user releases the email, so the person can register again
CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_alive
    ON users (email) WHERE deleted_on IS NULL;

-- Only one pending request per email
CREATE UNIQUE INDEX IF NOT EXISTS uq_request_email_pending
    ON registration_request (email)
    WHERE request_status = 'PENDING' AND deleted_on IS NULL;

CREATE INDEX IF NOT EXISTS idx_users_email            ON users (email);
CREATE INDEX IF NOT EXISTS idx_users_role             ON users (role);
CREATE INDEX IF NOT EXISTS idx_request_email          ON registration_request (email);
CREATE INDEX IF NOT EXISTS idx_request_status         ON registration_request (request_status);
CREATE INDEX IF NOT EXISTS idx_verification_token     ON verification_tokens (token);
CREATE INDEX IF NOT EXISTS idx_verification_request   ON verification_tokens (registration_request_id);
CREATE INDEX IF NOT EXISTS idx_audit_event_type       ON audit_logs (event_type);
CREATE INDEX IF NOT EXISTS idx_audit_user_id          ON audit_logs (user_id);
CREATE INDEX IF NOT EXISTS idx_audit_created_at       ON audit_logs (created_at);