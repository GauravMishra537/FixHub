-- V11: claims on tickets, and more actions in the ticket history.

-- one row per try of an employee to take a ticket.
-- no approval tick: the row is written as APPROVED at once and the ticket is assigned.
-- approval tick: the row stays PENDING until an admin decides.
CREATE TABLE IF NOT EXISTS ticket_claim (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     bigint       NOT NULL,
    user_id       bigint       NOT NULL,
    status        varchar(20)  NOT NULL,
    decided_by    bigint,
    decided_on    timestamp(6) with time zone,
    reject_reason varchar(255),
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT ck_ticket_claim_status CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN')),
    CONSTRAINT fk_ticket_claim_ticket FOREIGN KEY (ticket_id) REFERENCES ticket (id),
    CONSTRAINT fk_ticket_claim_user   FOREIGN KEY (user_id)   REFERENCES users (id)
);

-- a person has at most one live claim on a ticket
CREATE UNIQUE INDEX IF NOT EXISTS uq_ticket_claim_open
    ON ticket_claim (ticket_id, user_id)
    WHERE status IN ('PENDING', 'APPROVED') AND deleted_on IS NULL;

-- the admin list of claims that wait for a decision
CREATE INDEX IF NOT EXISTS idx_ticket_claim_pending
    ON ticket_claim (ticket_id)
    WHERE status = 'PENDING' AND deleted_on IS NULL;

CREATE INDEX IF NOT EXISTS idx_ticket_claim_user ON ticket_claim (user_id);

-- ticket_history: allow the new actions.
-- the old check is read, its values are kept, and the new ones are added,
-- so rows already in the table stay valid whatever V6 allowed.
DO $$
DECLARE
    old_name text;
    old_def  text;
    actions  text[];
BEGIN
    SELECT conname, pg_get_constraintdef(oid)
      INTO old_name, old_def
      FROM pg_constraint
     WHERE conrelid = 'ticket_history'::regclass
       AND contype = 'c'
       AND pg_get_constraintdef(oid) ILIKE '%action%'
     LIMIT 1;

    IF old_name IS NOT NULL THEN
        SELECT array_agg(t.x[1]) INTO actions
          FROM regexp_matches(old_def, '''([A-Z_]+)''', 'g') AS t(x);
        EXECUTE format('ALTER TABLE ticket_history DROP CONSTRAINT %I', old_name);
    END IF;

    actions := ARRAY(
        SELECT DISTINCT a
          FROM unnest(coalesce(actions, '{}'::text[])
                      || ARRAY['CLAIMED', 'CLAIM_WITHDRAWN', 'CLAIM_APPROVED', 'CLAIM_REJECTED',
                               'ASSIGNED', 'UNASSIGNED']) AS a
         ORDER BY a);

    EXECUTE format(
        'ALTER TABLE ticket_history ADD CONSTRAINT ck_ticket_history_action CHECK (action IN (%s))',
        (SELECT string_agg(quote_literal(a), ', ') FROM unnest(actions) AS a));
END $$;