-- V18: resource request. Four tables.
--   resource_category  the catalog tree: group, then sub-category. Each node may name the owning department.
--   resource_item      one requestable thing. PHYSICAL has a stock number, DIGITAL has none.
--   resource_approver  the one responsible person per department
--   resource_request   one row per ticket: what was asked and how it was decided
-- Stock is never stored as "left". Left = total_stock minus the quantity of requests with holding = true.
-- Seed: every category and item below. Safe to run again, nothing is added twice. Departments are linked by name.

-- ---------- the catalog tree ----------
CREATE TABLE IF NOT EXISTS resource_category (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL,
    -- empty for a group, the group id for a sub-category
    parent_id     bigint,
    icon          varchar(40),
    sort_order    integer      NOT NULL DEFAULT 0,
    active        boolean      NOT NULL DEFAULT true,
    -- who approves. a sub-category without one uses its group's department
    department_id bigint,
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT fk_resource_category_parent     FOREIGN KEY (parent_id)     REFERENCES resource_category (id),
    CONSTRAINT fk_resource_category_department FOREIGN KEY (department_id) REFERENCES department (id)
);

-- a name is unique among its siblings
CREATE UNIQUE INDEX IF NOT EXISTS uk_resource_category_name
    ON resource_category (coalesce(parent_id, 0), lower(name))
    WHERE deleted_on IS NULL;

-- ---------- one requestable thing ----------
CREATE TABLE IF NOT EXISTS resource_item (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     bigint       NOT NULL,
    name            varchar(150) NOT NULL,
    description     varchar(255),
    -- PHYSICAL: counted, has a stock. DIGITAL: licenses, cloud, tokens, no limit
    kind            varchar(10)  NOT NULL,
    total_stock     integer,
    max_per_request integer      NOT NULL DEFAULT 1,
    active          boolean      NOT NULL DEFAULT true,
    created_on      timestamp(6) with time zone NOT NULL,
    created_by      bigint,
    updated_on      timestamp(6) with time zone NOT NULL,
    updated_by      bigint,
    deleted_on      timestamp(6) with time zone,
    deleted_by      bigint,
    CONSTRAINT fk_resource_item_category FOREIGN KEY (category_id) REFERENCES resource_category (id),
    CONSTRAINT ck_resource_item_kind CHECK (kind IN ('PHYSICAL', 'DIGITAL')),
    -- physical needs a stock number, digital must not have one
    CONSTRAINT ck_resource_item_stock CHECK (
        (kind = 'PHYSICAL' AND total_stock IS NOT NULL AND total_stock >= 0)
        OR (kind = 'DIGITAL' AND total_stock IS NULL)),
    CONSTRAINT ck_resource_item_max CHECK (max_per_request >= 1 AND max_per_request <= 1000)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_resource_item_name
    ON resource_item (category_id, lower(name))
    WHERE deleted_on IS NULL;

-- ---------- the responsible person of a department ----------
CREATE TABLE IF NOT EXISTS resource_approver (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id bigint       NOT NULL,
    user_id       bigint       NOT NULL,
    created_on    timestamp(6) with time zone NOT NULL,
    created_by    bigint,
    updated_on    timestamp(6) with time zone NOT NULL,
    updated_by    bigint,
    deleted_on    timestamp(6) with time zone,
    deleted_by    bigint,
    CONSTRAINT fk_resource_approver_department FOREIGN KEY (department_id) REFERENCES department (id),
    CONSTRAINT fk_resource_approver_user       FOREIGN KEY (user_id)       REFERENCES users (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_resource_approver_department
    ON resource_approver (department_id)
    WHERE deleted_on IS NULL;

-- ---------- one request: this item, this many, for this person ----------
CREATE TABLE IF NOT EXISTS resource_request (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id         bigint       NOT NULL,
    item_id           bigint       NOT NULL,
    quantity          integer      NOT NULL,
    reason            varchar(500),
    needed_by         date,
    status            varchar(20)  NOT NULL DEFAULT 'PENDING_DEPT',
    -- true while the quantity counts against the stock: from the request until a reject or cancel
    holding           boolean      NOT NULL DEFAULT true,
    -- the department's person, kept as it was when the request was made. empty: no approver, goes to admin
    dept_approver_id  bigint,
    dept_decided_by   bigint,
    dept_decided_on   timestamp(6) with time zone,
    dept_note         varchar(500),
    admin_decided_by  bigint,
    admin_decided_on  timestamp(6) with time zone,
    admin_note        varchar(500),
    created_on        timestamp(6) with time zone NOT NULL,
    created_by        bigint,
    updated_on        timestamp(6) with time zone NOT NULL,
    updated_by        bigint,
    deleted_on        timestamp(6) with time zone,
    deleted_by        bigint,
    CONSTRAINT fk_resource_request_ticket   FOREIGN KEY (ticket_id)        REFERENCES ticket (id),
    CONSTRAINT fk_resource_request_item     FOREIGN KEY (item_id)          REFERENCES resource_item (id),
    CONSTRAINT fk_resource_request_approver FOREIGN KEY (dept_approver_id) REFERENCES users (id),
    CONSTRAINT ck_resource_request_quantity CHECK (quantity >= 1),
    CONSTRAINT ck_resource_request_status CHECK (
        status IN ('PENDING_DEPT', 'PENDING_ADMIN', 'APPROVED', 'REJECTED', 'CANCELLED', 'CLOSED'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_resource_request_ticket
    ON resource_request (ticket_id)
    WHERE deleted_on IS NULL;

-- the stock count: what is held per item
CREATE INDEX IF NOT EXISTS idx_resource_request_holding
    ON resource_request (item_id)
    WHERE holding AND deleted_on IS NULL;

-- the approver's queue: requests waiting for me
CREATE INDEX IF NOT EXISTS idx_resource_request_approver
    ON resource_request (dept_approver_id)
    WHERE status = 'PENDING_DEPT' AND deleted_on IS NULL;

